import * as esbuild from 'esbuild'
import { writeFileSync } from 'fs'

const { outputFiles } = await esbuild.build({
  entryPoints: ['src/browser-fallback.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: '_bsCrypto',
  platform: 'browser',
  write: false,
})

const iife = outputFiles[0].text.trim()

writeFileSync(
  'src/browser-fallback-bundle.ts',
  `/** Auto-generated by scripts/bundle-browser-fallback.mjs — do not edit */\nexport const BROWSER_FALLBACK_IIFE = ${JSON.stringify(iife)}\n`,
)

console.log('[build-stamp] browser fallback bundled (%d bytes)', iife.length)
